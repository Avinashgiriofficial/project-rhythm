import os
import json
from getpass import getpass
from typing import Optional, Literal
from pydantic import BaseModel, Field
from google import genai
from google.genai import types

# Enter your Gemini API key securely (won't be visible on screen)
if "GEMINI_API_KEY" not in os.environ:
    os.environ["GEMINI_API_KEY"] = getpass("Enter your Gemini API Key: ")

client = genai.Client(api_key=os.environ["GEMINI_API_KEY"])

# --- 1. Structured Output Schema ---
class SuggestedAction(BaseModel):
    type: Literal["none", "adjust_load", "add_break", "crisis_support"] = Field(
        description="Type of schedule action to offer the student."
    )
    study_hours_delta: int = Field(
        default=0,
        description="Change to study hours (e.g., -1 to lighten load, +1 to push harder, 0 for no change)."
    )
    extra_breaks: int = Field(
        default=0,
        description="Number of extra recovery breaks to add (0 to 2)."
    )
    button_label: Optional[str] = Field(
        default=None,
        description="Short button text for the UI, e.g., 'Apply Lighter Schedule (-1h Study, +1 Break)'."
    )

class GuideResponse(BaseModel):
    reply: str = Field(
        description="Empathetic 3-sentence response: 1) Validate emotion, 2) Ground in their schedule/streak, 3) Give one small next step."
    )
    suggested_action: SuggestedAction

# --- 2. Guardian System Prompt ---
GUARDIAN_SYSTEM_PROMPT = """
You are Rhythm, an emotionally intelligent daily planning guardian for students.
You are NOT a generic chatbot and NOT a therapist.

RESPONSE RULES:
1. Keep your reply to 3 short, natural sentences:
   - Sentence 1: Validate how the student feels without lecturing or toxic positivity.
   - Sentence 2: Reference their actual context (goal, streak, recent mood, or routine).
   - Sentence 3: Give ONE concrete, low-friction next step they can do right now.
2. Match the student's chosen Guardian Tone:
   - Gentle: Warm, slow-paced, prioritizes emotional safety and tiny wins.
   - Balanced: Supportive, calm, and structured.
   - Direct: Crisp, honest, no-fluff accountability.
3. Actionable Intelligence:
   - If the student is Sad, Tired, Stressed, or overwhelmed, suggest lightening the load (study_hours_delta: -1, extra_breaks: 1).
   - If the student is Motivated with a good streak, you may suggest a focused push (study_hours_delta: 1) or keep the plan steady (type: "none").
4. SAFETY GUARDRAIL (CRITICAL):
   - If the student expresses severe distress, hopelessness, or self-harm, DO NOT give study advice.
   - Set suggested_action.type to "crisis_support", study_hours_delta to 0, extra_breaks to 0, and button_label to "Call Tele-MANAS (14416)".
   - Respond with calm care, remind them they are not alone, and encourage reaching out to a trusted adult or Tele-MANAS (14416 in India).
"""

def ask_rhythm_guide(context_packet: dict) -> GuideResponse:
    prompt = f"Here is the student's current context packet:\n{json.dumps(context_packet, indent=2)}"
    response = client.models.generate_content(
        model="gemini-3.8-flash",
        contents=prompt,
        config=types.GenerateContentConfig(
            system_instruction=GUARDIAN_SYSTEM_PROMPT,
            response_mime_type="application/json",
            response_schema=GuideResponse,
            temperature=0.6,
        ),
    )
    return GuideResponse.model_validate_json(response.text)

