import time
from google.genai.errors import ServerError

def ask_rhythm_guide(context_packet: dict, retries: int = 3) -> GuideResponse:
    prompt = f"Here is the student's current context packet:\n{json.dumps(context_packet, indent=2)}"

    for attempt in range(retries):
        try:
            response = client.models.generate_content(
                model="gemini-3.8-flash",
                contents=prompt,
                config=types.GenerateContentConfig(
                    system_instruction=GUARDIAN_SYSTEM_PROMPT,
                    response_mime_type="application/json",
                    response_schema=GuideResponse,
                    temperature=0.6,
                ),
            )
            return GuideResponse.model_validate_json(response.text)
        except ServerError as e:
            if attempt < retries - 1:
                print(f"Server busy (503). Retrying in 3 seconds... (Attempt {attempt + 1}/{retries})")
                time.sleep(3)
            else:
                raise e